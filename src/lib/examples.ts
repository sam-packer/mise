// Sample feelings under the empty line, one set for each season: scenes and feelings, never bare
// mood words. Some are short, casual, and first person, to show that a feeling does not need to be
// written perfectly. Some belong to their season. Those name the weather and the light, not a month
// or a dated holiday, so they hold in both hemispheres.

export type Season = 'winter' | 'spring' | 'summer' | 'autumn';

const SEASONS: Season[] = ['winter', 'spring', 'summer', 'autumn'];

/**
 * The season on a date. Each one lasts three whole months: winter starts in December in the north,
 * and in June in the south.
 */
export function seasonOn(date: Date, south: boolean): Season {
	const quarter = Math.floor(((date.getMonth() + 1) % 12) / 3);
	return SEASONS[(quarter + (south ? 2 : 0)) % 4];
}

